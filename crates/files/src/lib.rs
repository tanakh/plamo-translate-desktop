//! TXT decoding, translation output assembly, and non-destructive export.

use std::io::{Read, Write};
use std::ops::Range;
use std::path::Path;

use encoding_rs::{UTF_16BE, UTF_16LE};
use thiserror::Error;

pub mod markdown;
pub mod office;

pub const MAX_FILE_BYTES: usize = 4 * 1024 * 1024;

#[derive(Debug, Error)]
pub enum FileError {
    #[error("no translated text could be saved")]
    NoTranslation,
    #[error("choose a .txt, .md, .pptx, .docx file")]
    Unsupported,
    #[error("file exceeds the 4 MiB limit")]
    TooLarge,
    #[error(
        "text must be UTF-8 or BOM-marked UTF-16 without binary control characters; convert other encodings to UTF-8 first"
    )]
    Encoding,
    #[error("translation returned inconsistent output ranges")]
    MismatchedResults,
    #[error("the original file cannot be overwritten")]
    OriginalDestination,
    #[error("destination already exists; choose a new filename")]
    DestinationExists,
    #[error(transparent)]
    Office(#[from] office::Error),
    #[error(transparent)]
    Io(#[from] std::io::Error),
}

#[derive(Debug, Clone)]
/// Decoded UTF-8/UTF-16 text, retaining BOM and line-ending information for export.
pub struct Document {
    source: String,
    bom: bool,
    pub converted_encoding: Option<&'static str>,
}

impl Document {
    /// Decode a TXT/Markdown input without guessing an ambiguous legacy encoding.
    pub fn open(bytes: &[u8], name: &str) -> Result<Self, FileError> {
        if !Path::new(name)
            .extension()
            .is_some_and(|e| e.eq_ignore_ascii_case("txt") || e.eq_ignore_ascii_case("md"))
        {
            return Err(FileError::Unsupported);
        }
        if bytes.len() > MAX_FILE_BYTES {
            return Err(FileError::TooLarge);
        }
        let (source, bom, converted_encoding) = decode(bytes)?;
        if source
            .chars()
            // A form feed is an ordinary page break in plain text (RFCs, licence texts).
            .any(|c| c.is_control() && !matches!(c, '\n' | '\r' | '\t' | '\u{c}'))
        {
            return Err(FileError::Encoding);
        }
        Ok(Self {
            source,
            bom,
            converted_encoding,
        })
    }

    pub fn source(&self) -> &str {
        &self.source
    }

    fn write_exact(&self, text: &str) -> Vec<u8> {
        let mut out = Vec::with_capacity(text.len() + 3);
        if self.bom {
            out.extend_from_slice(&[0xef, 0xbb, 0xbf]);
        }
        out.extend_from_slice(text.as_bytes());
        out
    }

    /// Encode translated text as UTF-8, preserving an existing UTF-8 BOM and uniform newlines.
    pub fn write(&self, translation: &str) -> Vec<u8> {
        let mut output = Vec::with_capacity(translation.len() + 3);
        if self.bom {
            output.extend_from_slice(&[0xef, 0xbb, 0xbf]);
        }
        if let Some(ending) = uniform_line_ending(&self.source) {
            // Preserve the file's convention even for new line breaks generated by the model.
            let normalized = translation.replace("\r\n", "\n").replace('\r', "\n");
            output.extend(normalized.replace('\n', ending).bytes());
        } else {
            output.extend_from_slice(translation.as_bytes());
        }
        output
    }
}

/// Mixed line endings are left as produced by the document translator.
fn uniform_line_ending(mut text: &str) -> Option<&'static str> {
    let mut ending = None;
    while let Some(i) = text.find(['\r', '\n']) {
        text = &text[i..];
        let next = if text.starts_with("\r\n") {
            "\r\n"
        } else if text.starts_with('\r') {
            "\r"
        } else {
            "\n"
        };
        if ending.is_some_and(|old| old != next) {
            return None;
        }
        ending = Some(next);
        text = &text[next.len()..];
    }
    ending
}

#[derive(Default)]
/// Collect streaming text and cuts; `finish` restores failed ranges from the source.
pub struct Translation {
    text: String,
    cuts: Vec<(Range<usize>, Range<usize>)>,
    invalid: bool,
}

impl Translation {
    pub fn append(&mut self, text: &str) {
        self.text.push_str(text);
    }

    pub fn rewind(&mut self, len: usize) {
        if len > self.text.len() || !self.text.is_char_boundary(len) {
            self.invalid = true;
            return;
        }
        self.text.truncate(len);
        self.cuts.retain(|(_, output)| output.end <= len);
    }

    pub fn cut(&mut self, source: Range<usize>, output: Range<usize>) {
        self.cuts.push((source, output));
    }

    /// Returns the repaired translation and the one-based input line of each replaced cut.
    pub fn finish(self, source: &str) -> Result<(String, Vec<usize>), FileError> {
        if self.invalid {
            return Err(FileError::MismatchedResults);
        }
        if self.cuts.is_empty() {
            return Ok((self.text, Vec::new()));
        }
        let mut result = String::with_capacity(self.text.len());
        let mut warnings = Vec::with_capacity(self.cuts.len());
        let mut output_end = 0;
        let mut source_end = 0;
        let mut line = 1;
        for (from, to) in self.cuts {
            let get = || {
                Some((
                    self.text.get(output_end..to.start)?,
                    self.text.get(to.clone())?,
                    source.get(from.clone())?,
                    source.get(source_end..from.start)?,
                ))
            };
            let Some((translated, _, original, preceding)) = get() else {
                return Err(FileError::MismatchedResults);
            };
            result.push_str(translated);
            result.push_str(original);
            line += line_breaks(preceding);
            warnings.push(line);
            line += line_breaks(original);
            output_end = to.end;
            source_end = from.end;
        }
        result.push_str(&self.text[output_end..]);
        Ok((result, warnings))
    }
}

fn line_breaks(text: &str) -> usize {
    text.bytes()
        .zip(text.bytes().skip(1).chain([0]))
        .filter(|&(b, next)| b == b'\n' || (b == b'\r' && next != b'\n'))
        .count()
}

fn decode(bytes: &[u8]) -> Result<(String, bool, Option<&'static str>), FileError> {
    if let Some(rest) = bytes.strip_prefix(&[0xef, 0xbb, 0xbf]) {
        return Ok((
            std::str::from_utf8(rest)
                .map_err(|_| FileError::Encoding)?
                .into(),
            true,
            None,
        ));
    }
    let utf16 = bytes
        .strip_prefix(&[0xff, 0xfe])
        .map(|b| (UTF_16LE, b, "UTF-16LE"))
        .or_else(|| {
            bytes
                .strip_prefix(&[0xfe, 0xff])
                .map(|b| (UTF_16BE, b, "UTF-16BE"))
        });
    if let Some((encoding, rest, label)) = utf16 {
        let text = encoding
            .decode_without_bom_handling_and_without_replacement(rest)
            .ok_or(FileError::Encoding)?;
        return Ok((text.into_owned(), false, Some(label)));
    }
    if let Ok(text) = std::str::from_utf8(bytes) {
        return Ok((text.into(), false, None));
    }
    Err(FileError::Encoding)
}

pub fn read_document(path: &Path) -> Result<Document, FileError> {
    read_text(path)
}

fn read_text(path: &Path) -> Result<Document, FileError> {
    let file = std::fs::File::open(path)?;
    if file.metadata()?.len() > MAX_FILE_BYTES as u64 {
        return Err(FileError::TooLarge);
    }
    let mut bytes = Vec::new();
    file.take(MAX_FILE_BYTES as u64 + 1)
        .read_to_end(&mut bytes)?;
    Document::open(&bytes, &path.to_string_lossy())
}

/// Never overwrites any existing file, including symlinks and aliases of the source.
/// Persisting with no-clobber also closes the race with a file created while the picker is open.
pub fn save_new(source: &Path, destination: &Path, bytes: &[u8]) -> Result<(), FileError> {
    if source == destination
        || (source
            .canonicalize()
            .ok()
            .zip(destination.canonicalize().ok())
            .is_some_and(|(a, b)| a == b))
    {
        return Err(FileError::OriginalDestination);
    }
    if std::fs::symlink_metadata(destination).is_ok() {
        return Err(FileError::DestinationExists);
    }
    let mut temp = tempfile::NamedTempFile::new_in(
        destination
            .parent()
            .filter(|p| !p.as_os_str().is_empty())
            .unwrap_or(Path::new(".")),
    )?;
    temp.write_all(bytes)?;
    temp.as_file().sync_all()?;
    temp.persist_noclobber(destination).map_err(|error| {
        if error.error.kind() == std::io::ErrorKind::AlreadyExists {
            FileError::DestinationExists
        } else {
            FileError::Io(error.error)
        }
    })?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn identity_roundtrip_preserves_bom_whitespace_and_crlf() {
        let input = format!(
            "\u{feff}  日本語😀\r\n\r\n\t{}  \n列1\t列2\r次の行",
            "長い文章。".repeat(120)
        );
        let doc = Document::open(input.as_bytes(), "a.TXT").unwrap();
        assert_eq!(doc.write(doc.source()), input.as_bytes());
    }

    #[test]
    fn converts_supported_encodings_without_replacement() {
        let original = "売上は増加しました。\r\n";
        let utf16: Vec<_> = [0xff, 0xfe]
            .into_iter()
            .chain(original.encode_utf16().flat_map(u16::to_le_bytes))
            .collect();
        let doc = Document::open(&utf16, "a.txt").unwrap();
        assert_eq!(doc.converted_encoding, Some("UTF-16LE"));
        assert_eq!(doc.write(doc.source()), original.as_bytes());
        // These byte strings can be decoded as Shift_JIS, but their encoding
        // cannot be inferred reliably. Never silently guess at a legacy codec.
        for bytes in [&b"caf\xe9"[..], &b"\xa4\xa2"[..], &b"\x93\xfa\x96\x7b"[..]] {
            assert!(matches!(
                Document::open(bytes, "a.txt"),
                Err(FileError::Encoding)
            ));
        }
        assert!(Document::open(&[0xff, 0xfe, 0x00], "a.txt").is_err());
        assert!(Document::open(b"binary\0data", "a.txt").is_err());
        let paged = "Page one.\n\u{c}Page two.\n";
        let doc = Document::open(paged.as_bytes(), "rfc.txt").unwrap();
        assert_eq!(doc.write(doc.source()), paged.as_bytes());
    }

    #[test]
    fn restores_bom_and_crlf_for_new_translation() {
        let doc = Document::open(b"\xef\xbb\xbfone\r\ntwo\r\n", "a.txt").unwrap();
        assert_eq!(doc.write("uno\ndos\n"), b"\xef\xbb\xbfuno\r\ndos\r\n");
    }

    #[test]
    fn export_never_overwrites_original_or_existing_destination() {
        let dir = tempfile::tempdir().unwrap();
        let source = dir.path().join("source.txt");
        let dest = dir.path().join("source.en.txt");
        std::fs::write(&source, "original").unwrap();
        assert!(save_new(&source, &source, b"bad").is_err());
        save_new(&source, &dest, b"translation").unwrap();
        assert!(save_new(&source, &dest, b"bad").is_err());
        assert_eq!(std::fs::read(&source).unwrap(), b"original");
        assert_eq!(std::fs::read(&dest).unwrap(), b"translation");
    }
}
